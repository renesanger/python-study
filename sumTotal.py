
total = 0
for num in range(101):
    total += num
print(total)




# story about the mathematician Carl Friedrich Gauss. 
# When Gauss was a boy, a teacher wanted to give the class some busywork. 
# The teacher told them to add up all the numbers from 0 to 100.

# (Young Gauss figured out a way to solve the problem in seconds. 
# There are 50 pairs of numbers that add up to 101: 1 + 100, 2 + 99, 3 + 98, and so on, until 50 + 51. 
# Since 50 × 101 is 5,050, the sum of all the numbers from 0 to 100 is 5,050. Clever kid!)